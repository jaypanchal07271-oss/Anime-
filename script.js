const JIKAN_BASE = "https://api.jikan.moe/v4";
const ANILIST_URL = "https://graphql.anilist.co";
const LIVE_LIMIT = 12;
const REQUEST_TIMEOUT = 9000;

const animeList = document.getElementById("animeList");
const animeDetail = document.getElementById("animeDetail");
const searchInput = document.getElementById("searchInput");
const genreChips = document.getElementById("genreChips");
const listStatus = document.getElementById("listStatus");

const state = {
  items: animeData,
  search: "",
  genre: "All",
  activeTitle: animeData[0].title,
  loading: true
};

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => {
    return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char];
  });
}

function formatNumber(value) {
  return typeof value === "number" ? value.toLocaleString("en-US") : "—";
}

async function fetchJson(url, options = {}) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT);
  try {
    const response = await fetch(url, { ...options, signal: controller.signal });
    if (!response.ok) throw new Error(`Request failed: ${response.status}`);
    return await response.json();
  } finally {
    clearTimeout(timer);
  }
}

function trimSynopsis(text) {
  const clean = String(text ?? "").split("[Written by")[0].replace(/\s+/g, " ").trim();
  if (!clean) return "No synopsis available for this title yet.";
  return clean.length > 600 ? `${clean.slice(0, 600).replace(/\s+\S*$/, "")}…` : clean;
}

function normalizeAnime(raw) {
  const genres = [...(raw.genres || []), ...(raw.themes || [])].map((genre) => genre.name);
  const cover = raw.images?.jpg?.large_image_url || raw.images?.jpg?.image_url || "";

  return {
    malId: raw.mal_id,
    title: raw.title_english || raw.title,
    year: String(raw.year || raw.aired?.prop?.from?.year || "—"),
    type: raw.type === "TV" ? "TV Series" : raw.type || "Anime",
    genres,
    genre: genres.slice(0, 4).join(" / ") || "Anime",
    studio: (raw.studios || []).map((studio) => studio.name).join(", ") || "Unknown studio",
    episodes: raw.episodes ? `${raw.episodes} Episodes` : "Ongoing",
    status: raw.status || "Unknown",
    score: raw.score ? raw.score.toFixed(2) : "—",
    summary: trimSynopsis(raw.synopsis),
    cover,
    banner: cover,
    ratings: {
      mal: raw.score ? raw.score.toFixed(2) : "—",
      rank: raw.rank ? `#${raw.rank}` : "—",
      members: formatNumber(raw.members)
    },
    characters: []
  };
}

async function fetchTopAnime() {
  const payload = await fetchJson(`${JIKAN_BASE}/top/anime?limit=${LIVE_LIMIT}&sfw`);
  return (payload.data || []).map(normalizeAnime).filter((anime) => anime.title && anime.cover);
}

async function fetchAniListExtras(malIds) {
  const query = `query ($ids: [Int]) {
    Page(perPage: 50) {
      media(idMal_in: $ids, type: ANIME) {
        idMal
        bannerImage
        characters(role: MAIN, perPage: 3, sort: [FAVOURITES_DESC]) {
          edges {
            node { name { full } image { large } }
            voiceActors(language: JAPANESE) { name { full } }
          }
        }
      }
    }
  }`;

  const payload = await fetchJson(ANILIST_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ query, variables: { ids: malIds } })
  });

  const extras = new Map();
  for (const media of payload.data?.Page?.media || []) {
    extras.set(media.idMal, {
      banner: media.bannerImage || null,
      characters: (media.characters?.edges || []).map((edge) => ({
        name: edge.node?.name?.full || "Unknown",
        role: "Main Character",
        image: edge.node?.image?.large || "",
        description: edge.voiceActors?.[0]?.name?.full
          ? `Voiced by ${edge.voiceActors[0].name.full}`
          : "Main character"
      }))
    });
  }
  return extras;
}

async function fetchJikanCharacters(malId) {
  const payload = await fetchJson(`${JIKAN_BASE}/anime/${malId}/characters`);
  return (payload.data || [])
    .filter((entry) => entry.role === "Main")
    .slice(0, 3)
    .map((entry) => ({
      name: entry.character?.name || "Unknown",
      role: entry.role || "Main Character",
      image: entry.character?.images?.jpg?.image_url || "",
      description: entry.voice_actors?.[0]?.person?.name
        ? `Voiced by ${entry.voice_actors[0].person.name}`
        : "Main character"
    }));
}

function getFilteredAnime() {
  const search = state.search.trim().toLowerCase();
  return state.items.filter((anime) => {
    const matchesSearch = !search || anime.title.toLowerCase().includes(search);
    const matchesGenre = state.genre === "All" || (anime.genres || []).includes(state.genre);
    return matchesSearch && matchesGenre;
  });
}

function getGenres() {
  const counts = new Map();
  for (const anime of state.items) {
    for (const genre of anime.genres || []) {
      counts.set(genre, (counts.get(genre) || 0) + 1);
    }
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 8)
    .map(([genre]) => genre);
}

function renderGenreChips() {
  const genres = ["All", ...getGenres()];
  if (!genres.includes(state.genre)) state.genre = "All";

  genreChips.innerHTML = genres
    .map(
      (genre) => `
        <button
          type="button"
          class="filter-btn ${genre === state.genre ? "active" : ""}"
          data-genre="${escapeHtml(genre)}"
          aria-pressed="${genre === state.genre}"
        >${escapeHtml(genre)}</button>
      `
    )
    .join("");
}

