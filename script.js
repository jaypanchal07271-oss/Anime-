async function loadCharacters(anime) {
  if (anime.characters.length || !anime.malId || anime.charactersRequested) return;
  anime.charactersRequested = true;

  try {
    anime.characters = await fetchJikanCharacters(anime.malId);
  } catch (error) {
    console.warn("Jikan characters unavailable, trying AniList", error);
    try {
      const extras = await fetchAniListExtras([anime.malId]);
      anime.characters = extras.get(anime.malId)?.characters || [];
    } catch (fallbackError) {
      console.warn("Character data unavailable", fallbackError);
      anime.charactersRequested = false;
      return;
    }
  }

  if (anime.characters.length && state.activeTitle === anime.title) {
    renderAnimeDetail(anime.title);
  }
}

async function enrichWithAniList() {
  const ids = state.items.map((anime) => anime.malId).filter(Boolean);
  if (!ids.length) return;

  try {
    const extras = await fetchAniListExtras(ids);
    let changed = false;
    for (const anime of state.items) {
      const extra = extras.get(anime.malId);
      if (!extra) continue;
      if (extra.banner) {
        anime.banner = extra.banner;
        changed = true;
      }
      if (!anime.characters.length && extra.characters.length) {
        anime.characters = extra.characters;
        changed = true;
      }
    }
    if (changed) renderAnimeDetail(state.activeTitle);
  } catch (error) {
    console.warn("Banner/character enrichment unavailable", error);
  }
}

function bindControls() {
  searchInput.addEventListener("input", (event) => {
    state.search = event.target.value;
    renderAnimeList(state.activeTitle);
  });

  genreChips.addEventListener("click", (event) => {
    const chip = event.target.closest(".filter-btn");
    if (!chip) return;
    state.genre = chip.dataset.genre;
    renderGenreChips();
    renderAnimeList(state.activeTitle);
  });
}

async function init() {
  bindControls();
  renderGenreChips();
  renderSkeletonList();
  renderSkeletonDetail();

  try {
    const liveItems = await fetchTopAnime();
    if (!liveItems.length) throw new Error("Empty Jikan response");
    state.items = liveItems;
  } catch (error) {
    console.warn("Live anime data unavailable, using bundled data", error);
    state.items = animeData;
  }

  state.loading = false;
  state.activeTitle = state.items[0].title;
  renderGenreChips();
  renderAnimeList(state.activeTitle);
  renderAnimeDetail(state.activeTitle);

  enrichWithAniList();
}

init();
