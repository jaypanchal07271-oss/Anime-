function renderAnimeList(activeTitle = state.activeTitle) {
  state.activeTitle = activeTitle;
  const visible = getFilteredAnime();

  if (listStatus) {
    listStatus.textContent = state.loading
      ? "Loading live anime data…"
      : `${visible.length} of ${state.items.length} titles`;
  }

  if (!visible.length) {
    animeList.innerHTML = `<p class="empty-state">No anime match your search.</p>`;
    return;
  }

  animeList.innerHTML = visible
    .map(
      (anime) => `
        <button class="anime-item ${anime.title === activeTitle ? "active" : ""}" data-title="${escapeHtml(anime.title)}">
          <img src="${escapeHtml(anime.cover)}" alt="${escapeHtml(anime.title)}" loading="lazy" />
          <div class="item-info">
            <h3>${escapeHtml(anime.title)}</h3>
            <div class="item-meta">
              <span>${escapeHtml(anime.type)}</span>
              <span class="item-score">${escapeHtml(anime.score)}</span>
            </div>
          </div>
        </button>
      `
    )
    .join("");

  document.querySelectorAll(".anime-item").forEach((item) => {
    item.addEventListener("click", () => {
      renderAnimeList(item.dataset.title);
      renderAnimeDetail(item.dataset.title);
    });
  });
}

